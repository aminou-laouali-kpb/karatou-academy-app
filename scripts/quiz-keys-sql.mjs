#!/usr/bin/env node
// Prints the SQL that loads the bundled lessons' quiz answer keys into
// app_private.karatou_quiz_keys, from supabase/quiz-keys.json (kept in sync
// with the lessons by src/data/quizKeys.test.ts).
//
//   node scripts/quiz-keys-sql.mjs > supabase/migrations/<timestamp>_quiz_keys_refresh.sql
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const keys = JSON.parse(readFileSync(resolve(root, 'supabase/quiz-keys.json'), 'utf8'));

const SLUG = /^[a-z0-9-]+$/;
const ANSWER = /^[A-Z]$/;

const rows = Object.entries(keys).map(([lesson, answers]) => {
  const [moduleSlug, courseId, extra] = lesson.split('/');
  if (extra !== undefined || !SLUG.test(moduleSlug ?? '') || !SLUG.test(courseId ?? '')) {
    throw new Error(`Invalid lesson key: ${lesson}`);
  }
  if (!Array.isArray(answers) || answers.length === 0 || !answers.every((answer) => ANSWER.test(answer))) {
    throw new Error(`Invalid answers for ${lesson}`);
  }
  return `  ('${moduleSlug}', '${courseId}', 'bundle', '*', '{${answers.join(',')}}')`;
});

process.stdout.write(`-- Generated by scripts/quiz-keys-sql.mjs from supabase/quiz-keys.json — do not edit by hand.
-- Answer keys of the lessons bundled with the app (${rows.length} lessons).
delete from app_private.karatou_quiz_keys where source = 'bundle';
insert into app_private.karatou_quiz_keys (module_slug, course_id, source, lang, answers) values
${rows.join(',\n')};
`);
